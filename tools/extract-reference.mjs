// Extracts the physics engine and the UI parameter defaults from the original
// browser player, so the reference engine is generated from the source rather
// than hand-copied. The only change made to the engine is the seeded RNG patch
// below; everything else is byte-for-byte what the player runs.
//
//   node tools/extract-reference.mjs           write reference/engine.mjs + player-defaults.json
//   node tools/extract-reference.mjs --check   fail if the committed files differ from a fresh extraction

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcPath = join(root, 'reference/original/player.html');
const html = readFileSync(srcPath, 'utf8');
const srcHash = createHash('sha256').update(html).digest('hex');

function between(text, start, end) {
  const i = text.indexOf(start);
  if (i < 0) throw new Error(`marker not found: ${start}`);
  const j = text.indexOf(end, i + start.length);
  if (j < 0) throw new Error(`end marker not found after: ${start}`);
  return text.slice(i + start.length, j);
}

// Replace exactly `count` occurrences, or fail: a silent zero-match patch would
// leave the reference engine unseeded and every golden render irreproducible.
function patch(text, from, to, count = 1) {
  const n = text.split(from).length - 1;
  if (n !== count) throw new Error(`patch expected ${count} match(es), found ${n}: ${from}`);
  return text.split(from).join(to);
}

// ---------------------------------------------------------------- engine
let engine = between(html, 'const ENGINE_SRC = `', '`;\nconst WORKLET_SRC');

// Seeded RNG. xorshift32, mirrored exactly by the C++ port. Math.random() is the
// only source of nondeterminism in the engine (the friction noise).
engine = patch(engine,
  'class BowlPhysics {\n  constructor(sr){',
  'class BowlPhysics {\n  constructor(sr){\n    this.rng=0x9E3779B9;');
engine = patch(engine,
  'setParams(o){ Object.assign(this.p,o); }\n  noteOn(vel){\n    const p=this.p;',
  'setParams(o){ Object.assign(this.p,o); }\n  seed(s){ this.rng=(s>>>0)||0x9E3779B9; }\n  rand(){ let s=this.rng; s^=s<<13; s^=s>>>17; s^=s<<5; this.rng=s>>>0; return this.rng/4294967296*2-1; }\n  noteOn(vel){\n    const p=this.p;');
engine = patch(engine,
  'const wn=(Math.random()*2-1);',
  'const wn=this.rand();');
// Seed each new voice from its note and a running note counter, so a render is a
// pure function of its event list.
engine = patch(engine,
  'this.tick=0; this.last=null;',
  'this.tick=0; this.last=null; this.notes=0;');
engine = patch(engine,
  'v.phys=this.make(midi); v.midi=midi; }',
  'v.phys=this.make(midi); v.midi=midi; this.notes++; if(v.phys.seed) v.phys.seed(Math.imul(midi+1,2654435761)^this.notes); }');
if (engine.includes('Math.random')) throw new Error('unpatched Math.random left in engine');

const engineOut =
`// GENERATED by tools/extract-reference.mjs from reference/original/player.html
// source sha256 ${srcHash}
// Do not edit. Regenerate, and run with --check in CI.
// Single change from the original: seeded xorshift32 friction noise (see extract script).
${engine.trim()}

export { BowlPhysics, BarPhysics, Synth };
`;

// ---------------------------------------------------------------- UI defaults
// The player's sliders push their defaults into the engine at start (pushAll),
// and those differ from the engine's constructor defaults (Q2 3500 vs 2500, ...).
// A reference render must start from what the player actually plays.
const specSrc = between(html, 'const GLASS=', '\nconst P=');
const { GLASS, BARS, PERF } = new Function(`const GLASS=${specSrc}; return {GLASS,BARS,PERF};`)();
const defaults = { glass: {}, bars: {}, perf: {} };
for (const [w, spec] of [['glass', GLASS], ['bars', BARS]])
  for (const g of spec) if (g.items) for (const it of g.items) defaults[w][it[0]] = it[5];
for (const it of PERF) defaults.perf[it[0]] = it[5];
const defaultsOut = JSON.stringify({ source_sha256: srcHash, ...defaults }, null, 2) + '\n';

// ---------------------------------------------------------------- write / check
const outputs = [
  [join(root, 'reference/engine.mjs'), engineOut],
  [join(root, 'reference/player-defaults.json'), defaultsOut],
];
if (process.argv.includes('--check')) {
  let bad = 0;
  for (const [p, text] of outputs) {
    let cur = '';
    try { cur = readFileSync(p, 'utf8'); } catch {}
    if (cur !== text) { console.error(`STALE: ${p} differs from a fresh extraction`); bad++; }
  }
  if (bad) process.exit(1);
  console.log('reference is current');
} else {
  for (const [p, text] of outputs) writeFileSync(p, text);
  console.log(`extracted from ${srcHash.slice(0, 12)}`);
}
